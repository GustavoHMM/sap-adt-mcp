export type UiKey = Key;
export type Translate = (key: UiKey, vars?: Record<string, string | number>) => string;

export function makeTranslate(lang: Lang): Translate {
  const catalog = lang === 'pt' ? pt : en;
  return (key, vars = {}) => catalog[key].replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}

const I18nContext = createContext<{ lang: Lang; t: Translate }>({ lang: 'pt', t: makeTranslate('pt') });

export function I18nProvider({ lang, children }: { lang: Lang; children: ReactNode }) {
  return <I18nContext.Provider value={{ lang, t: makeTranslate(lang) }}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
